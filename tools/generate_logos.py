"""Download real project logos and bake them into ASCII face textures.

Usage: python tools/generate_logos.py   (needs Pillow + resvg-py)
Writes: logo-data.js
"""
import io
import json
import urllib.request
from pathlib import Path

from PIL import Image, ImageOps
import resvg_py

ROOT = Path(__file__).resolve().parents[1]
SIZE = (30, 18)
RAMP = " .:-=+*#%@"

SOURCES = {
    "intro": ("png", "https://raw.githubusercontent.com/121kirillmorti/ascii-reel/main/assets/avatar.png"),
    "stickcommander": ("svg", "https://raw.githubusercontent.com/121kirillmorti/stickcommander/main/docs/assets/logo.svg"),
    "m5wheel": ("png", "https://raw.githubusercontent.com/121kirillmorti/m5wheel-ets2/main/assets/logo.png"),
    "justvibrait": ("png", "https://raw.githubusercontent.com/121kirillmorti/justvibrait/main/docs/screenshots/cover-en.png"),
    "tetris": ("svg", "https://raw.githubusercontent.com/121kirillmorti/tetris-you/main/docs/assets/logo.svg"),
    "github": ("svg", "https://cdn.simpleicons.org/github/ffffff"),
}


def load(kind, url):
    req = urllib.request.Request(url, headers={"User-Agent": "ascii-reel-generator"})
    with urllib.request.urlopen(req, timeout=30) as response:
        raw = response.read()
    if kind == "svg":
        svg = raw.decode("utf-8", "replace")
        if "<svg" not in svg and svg.strip().startswith("<"):
            svg = "<svg xmlns='http://www.w3.org/2000/svg'>" + svg + "</svg>"
        raw = resvg_py.svg_to_bytes(svg_string=svg, width=512, height=512)
    return Image.open(io.BytesIO(raw)).convert("RGBA")


def to_ascii(img):
    w, h = SIZE
    # Composite onto black so transparent logos become dark background.
    bg = Image.new("RGBA", img.size, (0, 0, 0, 255))
    bg.alpha_composite(img)
    gray = ImageOps.autocontrast(bg.convert("L").resize(SIZE, Image.Resampling.LANCZOS), cutoff=1)
    rows = []
    for y in range(h):
        row = ""
        for x in range(w):
            dx = (x - (w - 1) / 2) / (w / 2 - 1)
            dy = (y - (h - 1) / 2) / (h / 2 - 1)
            if dx * dx + dy * dy > 1.12:
                row += " "
                continue
            v = gray.getpixel((x, y))
            row += RAMP[max(0, min(len(RAMP) - 1, (v - 28) * len(RAMP) // 190))]
        rows.append(row)
    return "\n".join(rows)


art = {}
for key, (kind, url) in SOURCES.items():
    try:
        art[key] = to_ascii(load(kind, url))
        print(f"{key}: ok")
    except Exception as exc:  # keep the build usable if a remote asset breaks
        print(f"{key}: FAILED ({exc})")
        art[key] = "\n".join([" " * SIZE[0]] * SIZE[1])

payload = (
    "// AUTO-GENERATED by tools/generate_logos.py — do not edit by hand.\n"
    "window.LOGO_ART = " + json.dumps(art, ensure_ascii=False) + ";\n"
)
(ROOT / "logo-data.js").write_text(payload, encoding="utf-8")
