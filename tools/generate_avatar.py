"""Generate ASCII art + luminance map from a GitHub avatar.

Usage: python tools/generate_avatar.py
Writes: avatar-data.js (consumed by app.js)
Requires: Pillow
"""
import json
import urllib.request
from pathlib import Path

from PIL import Image

URL = "https://avatars.githubusercontent.com/u/191706072?v=4"
ROOT = Path(__file__).resolve().parents[1]

RAMP = " .:-=+*#%@"

req = urllib.request.Request(URL, headers={"User-Agent": "ascii-portfolio-generator"})
with urllib.request.urlopen(req, timeout=30) as response:
    raw = response.read()

img_path = ROOT / "assets" / "avatar.png"
img_path.parent.mkdir(parents=True, exist_ok=True)
img_path.write_bytes(raw)

source = Image.open(img_path).convert("RGB")


def char_for(value: int) -> str:
    """Map a pixel to ASCII, leaving the mid-grey avatar background empty."""
    index = (value - 110) * len(RAMP) // 90
    return RAMP[max(0, min(len(RAMP) - 1, index))]


# ASCII art: characters are ~2x taller than wide, so squash vertically by 2.
ascii_w, ascii_h = 80, 40
art = source.convert("L").resize((ascii_w, ascii_h), Image.Resampling.LANCZOS)
rows = []
for y in range(ascii_h):
    row = ""
    for x in range(ascii_w):
        dx = (x - ascii_w / 2 + 0.5) / (ascii_w / 2 - 3)
        dy = (y - ascii_h / 2 + 0.5) / (ascii_h / 2 - 3)
        row += " " if dx * dx + dy * dy > 1 else char_for(art.getpixel((x, y)))
    rows.append(row)
ascii_art = "\n".join(rows)

# Luminance map for wrapping the portrait around the 3D head.
luma_size = 64
luma_img = source.convert("L").resize((luma_size, luma_size), Image.Resampling.LANCZOS)
luma_rows = ["".join(char_for(luma_img.getpixel((x, y))) for x in range(luma_size)) for y in range(luma_size)]
luma_map = "\n".join(luma_rows)

payload = (
    "// AUTO-GENERATED by tools/generate_avatar.py — do not edit by hand.\n"
    "window.AVATAR_ART = " + json.dumps(ascii_art, ensure_ascii=False) + ";\n"
    "window.AVATAR_LUMA = " + json.dumps(luma_map, ensure_ascii=False) + ";\n"
    "window.AVATAR_RAMP = " + json.dumps(RAMP) + ";\n"
)
(ROOT / "avatar-data.js").write_text(payload, encoding="utf-8")
print(f"Wrote avatar-data.js ({ascii_w}x{ascii_h} art, {luma_size}x{luma_size} luma)")
